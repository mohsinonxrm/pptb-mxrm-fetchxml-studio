// Values
// ─────────────────────────────────────────────────────────────────────────────

/**
 * A condition value and its .NET type when the API gave one. The Web API returns
 * { "Type": "System.Int32", "Value": 10 }; other wrappers ({ "value": x }, { "Value": x }) and bare
 * values are accepted too.
 */
function unwrapValue(v: unknown): { type?: string; value: unknown } {
	if (v === null || typeof v !== "object") return { value: v };
	const obj = v as Record<string, unknown>;
	const keys = Object.keys(obj).filter((k) => !k.startsWith("@"));
	if (typeof obj.Type === "string" && "Value" in obj) return { type: obj.Type, value: obj.Value };
	if (keys.length === 1 && "value" in obj) return { value: obj.value };
	if (keys.length === 1 && "Value" in obj) return { value: obj.Value };
	return { value: v };
}

const NUMBER = /^-?\d+(\.\d+)?([eE][+-]?\d+)?$/;
const INTEGER = /^-?\d+$/;
const GUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** A condition value as a C# literal of the type the API reported */
function formatValue(v: unknown): string {
	const { type, value } = unwrapValue(v);
	if (value === null || value === undefined) return "null";
	const text = String(value);
	switch (type) {
		case "System.String":
			return csString(text);
		case "System.Int16":
		case "System.Int32":
		case "System.Byte":
			if (INTEGER.test(text)) return text;
			break;
		case "System.Int64":
			if (INTEGER.test(text)) return `${text}L`;
			break;
		case "System.Decimal":
			if (NUMBER.test(text)) return `${text}m`;
			break;
		case "System.Double":
			if (NUMBER.test(text)) return `${text}d`;
			break;
		case "System.Single":
			if (NUMBER.test(text)) return `${text}f`;
			break;
		case "System.Boolean":
			if (text === "true" || text === "false") return text;
			break;
		case "System.Guid":
			if (GUID.test(text)) return `new Guid(${csString(text)})`;
			break;
		case "System.DateTime":
			return `DateTime.Parse(${csString(text)})`;
	}
	// No (or an unexpected) type: keep what JSON says. A string stays a string, even when it's all
	// digits ("00123", a 20-digit code): only the API's type turns it into a number.
	if (typeof value === "boolean") return value ? "true" : "false";
	if (typeof value === "number") return Number.isFinite(value) ? text : csString(text);
	if (typeof value === "string") return GUID.test(value) && !type ? `new Guid(${csString(value)})` : csString(value);
	return `/* ${JSON.stringify(value).replace(/\*\//g, "* /")} */ null`;
}

/** A C# regular string literal: quotes, backslashes, line breaks and control characters escaped */
export function csString(s: string): string {
	let out = "";
	for (const ch of s) {
		const code = ch.codePointAt(0)!;
		if (ch === "\\") out += "\\\\";
		else if (ch === '"') out += '\\"';
		else if (ch === "\n") out += "\\n";
		else if (ch === "\r") out += "\\r";
		else if (ch === "\t") out += "\\t";
		else if (ch === "\0") out += "\\0";
		// Other control characters, and the characters C# treats as line breaks
		else if (code < 0x20 || code === 0x7f || code === 0x85 || code === 0x2028 || code === 0x2029) {
			out += `\\u${code.toString(16).padStart(4, "0")}`;
		} else out += ch;
	}
	return `"${out}"`;
}

/**
 * An enum member, e.g. ConditionOperator.Equal. The Web API returns names; a number is looked up
 * in the SDK's numbering, and an unknown one is written as a cast so the code still compiles.
 */
function enumRef(enumName: string, v: number | string | null | undefined, map: Record<number, string>): string {
	if (typeof v === "string" && /^[A-Za-z][A-Za-z0-9]*$/.test(v)) return `${enumName}.${v}`;
	if (typeof v === "number") return map[v] ? `${enumName}.${map[v]}` : `(${enumName})${v}`;
	return `${enumName}.${map[0]}`;
}

// ─────────────────────────────────────────────────────────────────────────────
// Layout helpers
// ─────────────────────────────────────────────────────────────────────────────

/** Lines of C# for one expression, without a trailing comma */
type Lines = string[];

/** Adds 4-space indentation (× depth) to each line */
function indent(lines: Lines, depth = 1): Lines {
	const pad = "    ".repeat(depth);
	return lines.map((l) => (l.length > 0 ? pad + l : l));
}

/** `head` with an object initializer of the given members (each gets a trailing comma) */
function block(head: string, members: Lines[]): Lines {
	if (members.length === 0) return [head];
	return [head, "{", ...indent(members.flatMap(withComma)), "}"];
}

/** `Name = value` */
function assign(name: string, value: Lines): Lines {
	return [`${name} = ${value[0]}`, ...value.slice(1)];
}

/** `Name = { item, item }`, a collection initializer */
function collection(name: string, items: Lines[]): Lines {
	return [`${name} =`, "{", ...indent(items.flatMap(withComma)), "}"];
}

function withComma(lines: Lines): Lines {
	return [...lines.slice(0, -1), `${lines[lines.length - 1]},`];
}

function hasFilterContent(f: QeFilterExpression): boolean {
	return (
		(f.Conditions != null && f.Conditions.length > 0) ||
		(f.Filters != null && f.Filters.length > 0) ||
		f.AnyAllFilterLinkEntity != null
	);
}
