/**
 * Generates C# SDK QueryExpression code from a Dataverse JSON QueryExpression object.
 *
 * The JSON object is the value of the `Query` property returned by the
 * FetchXmlToQueryExpression Web API function.
 *
 * Generated code targets:
 *   Microsoft.Xrm.Sdk.Query (QueryExpression, ColumnSet, FilterExpression,
 *   ConditionExpression, LinkEntity, OrderExpression, XrmAttributeExpression)
 *
 * The output was checked against the SDK reference (#178): a LinkEntity has `Columns` and
 * `LinkCriteria`, an OrderExpression takes (attribute, order, alias, entityName), and an
 * XrmAttributeExpression sets HasGroupBy and DateTimeGrouping as properties. Values keep the .NET
 * type the Web API reports, so "00123" stays a string and 1000.5 on a Decimal column is 1000.5m.
 * https://learn.microsoft.com/dotnet/api/microsoft.xrm.sdk.query
 */

import {
	type QeQueryExpression,
	type QeColumnSet,
	type QeXrmAttributeExpression,
	type QeFilterExpression,
	type QeConditionExpression,
	type QeLinkEntity,
	type QeAnyAllFilterLinkEntity,
	type QeOrderExpression,
	type QePagingInfo,
	LOGICAL_OPERATOR,
	JOIN_OPERATOR,
	ORDER_TYPE,
	CONDITION_OPERATOR,
	XRM_AGGREGATE_TYPE,
	XRM_DATETIME_GROUPING,
} from "./queryExpressionTypes";

// ─────────────────────────────────────────────────────────────────────────────
// Public entry point
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Converts a Dataverse QueryExpression JSON object to C# SDK source code.
 * @param qe  The parsed QueryExpression (from `FetchXmlToQueryExpression().Query`).
 * @returns   C# code string using `Microsoft.Xrm.Sdk.Query` types.
 */
export function generateCSharpQueryExpression(qe: QeQueryExpression): string {
	const props: Lines[] = [assign("ColumnSet", emitColumnSet(qe.ColumnSet ?? { AllColumns: false }))];
	if (qe.Criteria && hasFilterContent(qe.Criteria)) props.push(assign("Criteria", emitFilter(qe.Criteria)));
	if (qe.LinkEntities?.length) props.push(collection("LinkEntities", qe.LinkEntities.map((le) => emitLinkEntity(le))));
	if (qe.Orders?.length) props.push(collection("Orders", qe.Orders.map(emitOrder)));
	if (qe.TopCount != null) props.push([`TopCount = ${qe.TopCount}`]);
	if (qe.Distinct) props.push(["Distinct = true"]);
	if (qe.NoLock) props.push(["NoLock = true"]);
	if (qe.QueryHints) props.push([`QueryHints = ${csString(qe.QueryHints)}`]);
	const paging = emitPageInfo(qe.PageInfo);
	if (paging) props.push(assign("PageInfo", paging));

	const query = block(`new QueryExpression(${csString(qe.EntityName)})`, props);
	query[0] = `var query = ${query[0]}`;
	query[query.length - 1] += ";";
	return [
		"// Generated by FetchXML Studio — Code Generation Panel",
		"// Requires: Microsoft.PowerPlatform.Dataverse.Client or Microsoft.CrmSdk.CoreAssemblies",
		"",
		...query,
	].join("\n");
}

// ─────────────────────────────────────────────────────────────────────────────
// ColumnSet
// ─────────────────────────────────────────────────────────────────────────────

function emitColumnSet(cs: QeColumnSet): Lines {
	// Aggregate query: AttributeExpressions, with AllColumns left false (not the ColumnSet(bool) constructor)
	if (cs.AttributeExpressions?.length) {
		return block("new ColumnSet", [collection("AttributeExpressions", cs.AttributeExpressions.map(emitAttributeExpression))]);
	}
	if (cs.AllColumns) return ["new ColumnSet(true)"];
	if (!cs.Columns?.length) return ["new ColumnSet()"];
	return [`new ColumnSet(${cs.Columns.map(csString).join(", ")})`];
}

/** Whether a link's Columns says anything (an empty ColumnSet is the default) */
const hasColumns = (cs: QeColumnSet | null | undefined): cs is QeColumnSet =>
	!!cs && (cs.AllColumns || !!cs.Columns?.length || !!cs.AttributeExpressions?.length);

function emitAttributeExpression(ae: QeXrmAttributeExpression): Lines {
	const args = [csString(ae.AttributeName), enumRef("XrmAggregateType", ae.AggregateType ?? 0, XRM_AGGREGATE_TYPE)];
	if (ae.Alias) args.push(csString(ae.Alias));
	const props: Lines[] = [];
	if (ae.HasGroupBy) props.push(["HasGroupBy = true"]);
	const grouping = ae.DateTimeGrouping;
	if (grouping != null && grouping !== 0 && grouping !== "None") {
		props.push([`DateTimeGrouping = ${enumRef("XrmDateTimeGrouping", grouping, XRM_DATETIME_GROUPING)}`]);
	}
	return block(`new XrmAttributeExpression(${args.join(", ")})`, props);
}

// ─────────────────────────────────────────────────────────────────────────────
// FilterExpression
// ─────────────────────────────────────────────────────────────────────────────

function emitFilter(filter: QeFilterExpression): Lines {
	const props: Lines[] = [];
	if (filter.Conditions?.length) props.push(collection("Conditions", filter.Conditions.map(emitCondition)));
	if (filter.Filters?.length) props.push(collection("Filters", filter.Filters.map(emitFilter)));
	if (filter.AnyAllFilterLinkEntity) {
		props.push(assign("AnyAllFilterLinkEntity", emitLinkEntity(filter.AnyAllFilterLinkEntity, true)));
	}
	if (filter.FilterHint) props.push([`FilterHint = ${csString(filter.FilterHint)}`]);
	if (filter.IsQuickFindFilter) props.push(["IsQuickFindFilter = true"]);
	return block(`new FilterExpression(${enumRef("LogicalOperator", filter.FilterOperator, LOGICAL_OPERATOR)})`, props);
}

function emitCondition(cond: QeConditionExpression): Lines {
	const args: string[] = [];
	if (cond.EntityName) args.push(csString(cond.EntityName));
	args.push(csString(cond.AttributeName), enumRef("ConditionOperator", cond.Operator, CONDITION_OPERATOR));
	// The API returns no values for operators that take none (Null, ThisYear, EqualUserId, …)
	const values = cond.Values ?? [];

	if (cond.CompareColumns && values.length > 0) {
		// The values are other columns' names
		const columns = values.map((v) => csString(String(unwrapValue(v).value)));
		args.push("compareColumns: true", columns.length === 1 ? columns[0] : `new object[] { ${columns.join(", ")} }`);
	} else if (values.length === 1) {
		const value = formatValue(values[0]);
		// A bare null matches the object, object[] and ICollection overloads alike
		args.push(value === "null" ? "(object)null" : value);
	} else if (values.length > 1) {
		const literals = values.map(formatValue);
		// (attribute, operator, true, x) would bind to the compareColumns overload: pass an array
		const firstIsBool = typeof unwrapValue(values[0]).value === "boolean";
		args.push(...(firstIsBool ? [`new object[] { ${literals.join(", ")} }`] : literals));
	}
	return [`new ConditionExpression(${args.join(", ")})`];
}

// ─────────────────────────────────────────────────────────────────────────────
// LinkEntities
// ─────────────────────────────────────────────────────────────────────────────

/**
 * A LinkEntity. For an any/all filter link (FilterExpression.AnyAllFilterLinkEntity) the columns
 * are left out: Dataverse ignores them.
 */
function emitLinkEntity(le: QeLinkEntity | QeAnyAllFilterLinkEntity, anyAllFilter = false): Lines {
	const joinOp = enumRef("JoinOperator", le.JoinOperator ?? 0, JOIN_OPERATOR);
	const head = `new LinkEntity(${[le.LinkFromEntityName, le.LinkToEntityName, le.LinkFromAttributeName, le.LinkToAttributeName]
		.map(csString)
		.join(", ")}, ${joinOp})`;
	const props: Lines[] = [];
	if (le.EntityAlias) props.push([`EntityAlias = ${csString(le.EntityAlias)}`]);
	if (!anyAllFilter && hasColumns(le.Columns)) props.push(assign("Columns", emitColumnSet(le.Columns)));
	if (le.LinkCriteria && hasFilterContent(le.LinkCriteria)) props.push(assign("LinkCriteria", emitFilter(le.LinkCriteria)));
	if (le.LinkEntities?.length) props.push(collection("LinkEntities", le.LinkEntities.map((child) => emitLinkEntity(child))));
	if (le.Orders?.length) props.push(collection("Orders", le.Orders.map(emitOrder)));
	return block(head, props);
}

// ─────────────────────────────────────────────────────────────────────────────
// Orders and paging
// ─────────────────────────────────────────────────────────────────────────────

/** OrderExpression(attributeName, orderType[, alias[, entityName]]) */
function emitOrder(o: QeOrderExpression): Lines {
	const args = [csString(o.AttributeName), enumRef("OrderType", o.OrderType ?? 0, ORDER_TYPE)];
	if (o.EntityName) args.push(o.Alias ? csString(o.Alias) : "null", csString(o.EntityName));
	else if (o.Alias) args.push(csString(o.Alias));
	return [`new OrderExpression(${args.join(", ")})`];
}

/** PageInfo when the query sets paging; the API always returns one, empty by default */
function emitPageInfo(p: QePagingInfo | null | undefined): Lines | undefined {
	if (!p) return undefined;
	const props: Lines[] = [];
	if (p.Count) props.push([`Count = ${p.Count}`]);
	if (p.PageNumber && (p.Count || p.PageNumber > 1)) props.push([`PageNumber = ${p.PageNumber}`]);
	if (p.ReturnTotalRecordCount) props.push(["ReturnTotalRecordCount = true"]);
	if (p.PagingCookie) props.push([`PagingCookie = ${csString(p.PagingCookie)}`]);
	return props.length > 0 ? block("new PagingInfo", props) : undefined;
}

